'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');
const subscribe = (channel, callback) => { const listener = (_, value) => callback(value); ipcRenderer.on(channel, listener); return () => ipcRenderer.removeListener(channel, listener); };
contextBridge.exposeInMainWorld('remoteDesktop', {
  getSettings: () => ipcRenderer.invoke('app:get-settings'),
  saveServer: input => ipcRenderer.invoke('app:save-server', input),
  getSystemInfo: () => ipcRenderer.invoke('ssh:system-info'),
  setDesktop: remotePath => ipcRenderer.invoke('ssh:set-desktop', remotePath),
  checkFileAccess: remotePath => ipcRenderer.invoke('ssh:file-access', remotePath),
  saveSettings: patch => ipcRenderer.invoke('app:save-settings', patch),
  choosePrivateKey: () => ipcRenderer.invoke('app:choose-private-key'),
  quitFullscreen: () => ipcRenderer.invoke('app:quit-fullscreen'),
  connect: input => ipcRenderer.invoke('ssh:connect', input),
  disconnect: () => ipcRenderer.invoke('ssh:disconnect'),
  closeTerminal: id => ipcRenderer.invoke('terminal:close', id),
  discoverDesktop: create => ipcRenderer.invoke('ssh:discover-desktop', create),
  list: remotePath => ipcRenderer.invoke('ssh:list', remotePath),
  image: remotePath => ipcRenderer.invoke('ssh:image', remotePath),
  openVideo: remotePath => ipcRenderer.invoke('video:open', remotePath),
  releaseVideo: id => ipcRenderer.invoke('video:release', id),
  download: (remotePath, id, destination) => ipcRenderer.invoke('ssh:download', remotePath, id, destination),
  chooseUpload: kind => ipcRenderer.invoke('transfer:choose-local', kind),
  acceptDroppedFiles: files => ipcRenderer.invoke('transfer:accept-drop', Array.from(files).map(file => webUtils.getPathForFile(file)).filter(Boolean)),
  chooseDownloadDirectory: () => ipcRenderer.invoke('transfer:choose-download-directory'),
  upload: (localPath, remoteDirectory, id) => ipcRenderer.invoke('transfer:upload', localPath, remoteDirectory, id),
  listTransfers: () => ipcRenderer.invoke('transfer:list'),
  removeTransfer: id => ipcRenderer.invoke('transfer:remove', id),
  clearTransferHistory: () => ipcRenderer.invoke('transfer:clear'),
  openTransferTarget: id => ipcRenderer.invoke('transfer:open-target', id),
  openDocument: (remotePath, options) => ipcRenderer.invoke('workbench:open', remotePath, options),
  openBrowser: url => ipcRenderer.invoke('browser:open', url),
  layoutBrowser: (id, bounds, hidden) => ipcRenderer.invoke('browser:layout', id, bounds, hidden),
  closeBrowser: id => ipcRenderer.invoke('browser:close', id),
  onBrowserEvent: callback => subscribe('browser:event', callback),
  getActivitySnapshot: () => ipcRenderer.invoke('activity:snapshot'),
  onActivityEvent: callback => subscribe('activity:event', callback),
  cancelDownload: id => ipcRenderer.invoke('ssh:cancel-download', id),
  openLocal: filePath => ipcRenderer.invoke('ssh:open-local', filePath),
  send: message => ipcRenderer.send('desktop:send', message),
  onMessage: callback => subscribe('desktop:message', callback),
  onDownloadProgress: callback => subscribe('download:progress', callback)
});
