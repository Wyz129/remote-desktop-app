'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');
const fsp = require('node:fs/promises');
const { _electron: electron } = require('playwright');
const { createSshFixture } = require('./helpers/ssh-fixture.cjs');
const project = path.resolve(__dirname, '..');

test('real isolated Electron process, preload IPC, SSH desktop, image, download and reconnect', { timeout: 180000 }, async t => {
  const fixture = await createSshFixture();
  let application;
  t.after(async () => { await application?.close(); await fixture.close(); });
  const userData = path.join(fixture.root, 'electron-user-data');
  await fsp.mkdir(userData);
  await fixture.put('Desktop/notes.txt', 'Real Electron -> IPC -> SSH fixture\n');
  await fixture.put('Desktop/pixel.png', Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/a9sAAAAASUVORK5CYII=', 'base64'));
  await fixture.put('Desktop/projects/example.txt', 'nested');
  await fsp.writeFile(path.join(userData, 'settings.json'), JSON.stringify({ downloadThreshold: 1048576, host: fixture.config.host, port: fixture.config.port, username: fixture.username, knownHosts: { [`${fixture.config.host}:${fixture.config.port}`]: fixture.fingerprint } }));
  const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE;
  const executablePath = process.env.REMOTE_DESKTOP_TEST_EXE;
  application = await electron.launch({ ...(executablePath ? { executablePath } : {}), args: [...(executablePath ? [] : [project]), '--smoke-test', `--user-data-dir=${userData}`], env });
  const page = await application.firstWindow();
  page.setDefaultTimeout(12000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.locator('#connectionDialog[open]').waitFor();
  assert.equal(await page.evaluate(() => typeof window.remoteDesktop?.connect), 'function');
  await page.evaluate(() => { window.ipcEvents = []; window.remoteDesktop.onMessage(value => window.ipcEvents.push(value)); });
  assert.equal(await page.evaluate(() => typeof window.require), 'undefined');
  assert.equal(await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isFullScreen()), true);
  const systemDownloads = await application.evaluate(({ app }) => app.getPath('downloads'));
  assert.equal((await page.evaluate(() => window.remoteDesktop.getSettings())).downloadsPath, systemDownloads);
  await application.evaluate(({ app }, target) => app.setPath('downloads', target), fixture.downloads);
  await page.locator('#sshPassword').fill(fixture.password);
  await page.locator('#connectSubmit').click();
  await page.locator('#connectionDialog').waitFor({ state: 'hidden' });
  await page.locator(`#icons [data-path="${fixture.home}/Desktop/notes.txt"]`).waitFor();
  assert.equal(await page.locator('#sshPassword').inputValue(), '');
  assert.equal(await page.locator('#desktopPath').textContent(), `${fixture.home}/Desktop`);
  await page.locator(`#icons [data-path="${fixture.home}/Desktop/projects"]`).dblclick();
  await page.locator('.window .entry').filter({ hasText: 'example.txt' }).waitFor();
  await page.locator('.window [data-window-action="close"]').click();
  await page.locator(`#icons [data-path="${fixture.home}/Desktop/pixel.png"]`).dblclick();
  await page.waitForFunction(() => document.querySelector('.image-window img')?.naturalWidth === 1);
  await page.locator('.image-window [data-image-action="in"]').click();
  assert.ok(Number(await page.locator('.image-window').getAttribute('data-image-scale')) > 1);
  await page.locator('.image-window [data-window-action="close"]').click();
  await page.locator(`#icons [data-path="${fixture.home}/Desktop/notes.txt"]`).click({ button: 'right' });
  await page.locator('#context [data-action="download"]').click();
  await page.waitForFunction(() => document.querySelector('.download-status')?.textContent.includes('已完成'));
  assert.equal(await fsp.readFile(path.join(fixture.downloads, 'notes.txt'), 'utf8'), 'Real Electron -> IPC -> SSH fixture\n');
  assert.ok(fixture.calls.exec.some(command => command.startsWith('cat -- ')));
  await page.locator('#closeDownloads').click();
  await page.evaluate(() => window.remoteDesktop.send({ type: 'pinApp', app: { program: 'shell', label: 'Shell' } }));
  await page.locator('#pinnedApps').getByText('Shell', { exact: true }).waitFor();
  await page.evaluate(() => window.remoteDesktop.send({ type: 'pinApp', app: { program: 'vim', label: 'Vim' } }));
  await page.locator('#pinnedApps').getByText('Vim', { exact: true }).waitFor();
  assert.equal(await page.locator('#pinnedApps .pinned-app').count(), 2);
  await page.evaluate(() => window.remoteDesktop.send({ type: 'unpinApp', id: 'pinned-shell' }));
  await page.waitForFunction(() => document.querySelectorAll('#pinnedApps .pinned-app').length === 1);
  await page.keyboard.press('Control+Alt+t');
  await page.waitForFunction(() => window.ipcEvents.some(message => message.type === 'terminalOpened'));
  const terminalId = await page.evaluate(() => window.ipcEvents.find(message => message.type === 'terminalOpened').id);
  await page.evaluate(id => window.remoteDesktop.send({ type: 'terminalInput', id, data: 'Electron 中文 input\r' }), terminalId);
  await page.waitForFunction(() => window.ipcEvents.filter(message => message.type === 'terminalData').map(message => message.data).join('').includes('fixture-echo:Electron 中文 input'));
  await page.evaluate(id => window.remoteDesktop.send({ type: 'terminalResize', id, cols: 99, rows: 33 }), terminalId);
  await page.waitForTimeout(100);
  assert.ok(fixture.calls.resize.some(size => size.cols === 99 && size.rows === 33));
  await page.locator('.terminal-window [data-window-action="close"]').click();
  await page.locator(`#icons [data-path="${fixture.home}/Desktop/notes.txt"]`).dblclick();
  await page.waitForFunction(() => window.ipcEvents.filter(message => message.type === 'terminalOpened').length === 2);
  assert.ok(fixture.calls.exec.some(command => command.includes(`exec vim -- '${fixture.home}/Desktop/notes.txt'`)));
  await page.locator('.terminal-window [data-window-action="close"]').click();
  await page.locator('#fullscreen').click();
  await page.waitForTimeout(150);
  assert.equal(await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isFullScreen()), false);
  await page.evaluate(() => window.remoteDesktop.disconnect());
  await page.waitForFunction(() => document.querySelectorAll('#icons .icon').length === 0);
  await page.locator('#connectButton').click();
  await page.locator('#sshPassword').fill(fixture.password); await page.locator('#connectSubmit').click();
  await page.locator('#connectionDialog').waitFor({ state: 'hidden' });
  await page.locator('#pinnedApps').getByText('Vim', { exact: true }).waitFor();
  assert.equal(await page.locator('#pinnedApps .pinned-app').count(), 1);
  const diskSettings = await fsp.readFile(path.join(userData, 'settings.json'), 'utf8');
  assert.equal(diskSettings.includes(fixture.password), false);
  assert.equal(/privateKey|passphrase|password/.test(diskSettings), false);
  assert.deepEqual(errors, []);
  await fsp.mkdir(path.join(project, 'artifacts'), { recursive: true });
  await page.screenshot({ path: path.join(project, 'artifacts', executablePath ? 'packaged-electron.png' : 'electron-smoke.png') });
  await fsp.writeFile(path.join(project, 'artifacts', executablePath ? 'packaged-electron-results.json' : 'electron-results.json'), JSON.stringify({ passed: true, electron: await application.evaluate(() => process.versions.electron), systemDownloads, boundary: 'Actual Electron main/preload/renderer and TCP SSH/SFTP loopback fixture; not user server', execRequests: fixture.calls.exec.length }, null, 2));
});
